    </div>
</div>

<div class="hc-topic" id="rd-release">
    <h3><x-icon name="log-out" /> Leaving the display</h3>
    <p><strong>Leave Room</strong> in the display's settings goes back to the room list. When the room ends (End Room in Event Control) every display showing it goes back to the list on its own.</p>
</div>
