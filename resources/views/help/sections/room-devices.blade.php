<div class="hc-topic" id="rd-what">
    <h3><x-icon name="tablet" /> What a room display is</h3>
    <p>A room display shows a running room's live queue on a screen in the room — a projector, a TV or a spare tablet — so groups can see who is presenting and who is next. It needs no account, and any number of screens can show the same room.</p>
    <p>A display is <strong>view only</strong>. Panelists do not sign in on it: they join the room from their own account in <a href="#pn-join">Live Room</a>.</p>
</div>

<div class="hc-topic" id="rd-check">
    <h3><x-icon name="monitor" /> Checking a device</h3>
    <p>Before the event, open <code>/room-session/device-check</code> on the device. It reports the browser and whether it supports what the room screens need. It needs no account, so it works even on a device that cannot get any further. Update the browser (or use another device) if it reports a problem.</p>
    <div class="hc-note hc-note-tip"><x-icon name="lightbulb" /><p>Keep the display on a reliable network, and turn off auto-lock so the screen does not sleep mid-presentation.</p></div>
</div>

<div class="hc-topic" id="rd-setup">
    <h3><x-icon name="settings" /> Showing a room</h3>
    <ol class="hc-steps">
        <li class="hc-step"><div class="hc-step-marker">1</div><div class="hc-step-body"><div class="hc-step-head"><x-icon name="play" /> Start the room</div><p class="hc-step-text">In <strong>Event Control</strong>, press <strong>Start Room</strong>.</p></div></li>
        <li class="hc-step"><div class="hc-step-marker">2</div><div class="hc-step-body"><div class="hc-step-head"><x-icon name="monitor" /> Open it on the display</div><p class="hc-step-text">On the display, open <code>/room-session</code>, choose the room under its category and press <strong>Open Room</strong>.</p></div></li>
    </ol>
</div>

<div class="hc-topic" id="rd-screen">
    <h3><x-icon name="tablet" /> What the display shows</h3>
    <div class="hc-options">
        <div class="hc-option"><div class="hc-option-icon"><x-icon name="list-check" /></div><div><div class="hc-option-title">Room Queue</div><p>Today's counts, the current or last group, who is called and next, and <strong>View All</strong> for the full queue in a side panel.</p></div></div>
        <div class="hc-option"><div class="hc-option-icon"><x-icon name="clock" /></div><div><div class="hc-option-title">Status card</div><p>The group on stage, its timer, payment status, break warnings and notices from the Administrator.</p></div></div>
